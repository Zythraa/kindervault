const parseApiResponse = async (response) => {
  let data;
  try {
    data = await response.json();
  } catch (error) {
    data = response.ok ? {} : {error: `Request failed (${response.status})`};
  }
  if (response.status === 401) {
    window.dispatchEvent(new CustomEvent('kv:session-unauthorized', {detail:data}));
  } else if (response.ok) {
    window.dispatchEvent(new CustomEvent('kv:session-confirmed'));
  }
  if (data && typeof data.error === 'string') data.error = window.kvT(data.error);
  return data;
};

const api = {
  get:    (url)       => fetch(url).then(parseApiResponse),
  post:   (url, body) => fetch(url, { method:'POST',   headers:apiHeaders(), body:JSON.stringify(body) }).then(parseApiResponse),
  put:    (url, body) => fetch(url, { method:'PUT',    headers:apiHeaders(), body:JSON.stringify(body) }).then(parseApiResponse),
  delete: (url)       => fetch(url, { method:'DELETE', headers:apiHeaders() }).then(parseApiResponse),
};

